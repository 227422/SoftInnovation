from typing import Protocol


class NoticeStore(Protocol):
    def save_raw(self, raw, now, *, job=None) -> bool: ...
    def publish(self, document, analysis, now, *, job=None) -> bool: ...
    def get(self, notice_id: str) -> dict | None: ...
    def list(self, school_id='csu', *, limit=None) -> list[dict]: ...
    def raw(self, notice_id, content_version) -> dict | None: ...
    def record_failure(self, notice_id, code, message, now, *, job=None) -> bool: ...
