from __future__ import annotations
from datetime import datetime
from typing import Protocol


class SourceStore(Protocol):
    def list(self, school_id: str | None = None) -> list[dict]: ...
    def get(self, source_id: str) -> dict | None: ...
    def sync(self, sources: list[dict], now: datetime) -> None: ...
    def schedule(self, now: datetime, interval: int = 1200, source_ids=None, force=False) -> int: ...
    def update_status(self, source_id, now, **changes) -> bool: ...
