from typing import Protocol


class JobStore(Protocol):
    def enqueue(self, job_id, kind, source_id, payload, now, *, repeat=False) -> bool: ...
    def claim(self, now, lease_seconds=600, kinds=None) -> dict | None: ...
    def finish(self, job, now) -> bool: ...
    def retry(self, job, now, *, delay=30, error='retry') -> bool: ...
    def counts(self) -> dict: ...


class HTTPReader(Protocol):
    def get(self, url, allowed_hosts, *, max_bytes=8388608) -> dict: ...
    def probe(self, url, allowed_hosts) -> dict: ...
